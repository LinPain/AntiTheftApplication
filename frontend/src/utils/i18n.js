export function getLanguage() {
  if (typeof window === "undefined") return "vi";
  const saved = localStorage.getItem(LANGUAGE_KEY);
  return SUPPORTED_LANGUAGES.includes(saved) ? saved : "vi";
}

export function setLanguagePreference(language) {
  const next = SUPPORTED_LANGUAGES.includes(language) ? language : "vi";
  localStorage.setItem(LANGUAGE_KEY, next);
  if (typeof window !== "undefined") {
    window.dispatchEvent(new Event("sat-language-change"));
  }
  return next;
}

export function t(key, fallback = "") {
  const language = getLanguage();
  const value = translations[language]?.[key] || translations.vi[key] || fallback || key;
  return value;
}

export function useLanguage() {
  const [language, setLanguageState] = useState(getLanguage());

  useEffect(() => {
    const sync = () => setLanguageState(getLanguage());
    sync();
    window.addEventListener("storage", sync);
    window.addEventListener("sat-language-change", sync);
    return () => {
      window.removeEventListener("storage", sync);
      window.removeEventListener("sat-language-change", sync);
    };
  }, []);

  const setLanguage = (nextLanguage) => {
    const resolved = setLanguagePreference(nextLanguage);
    setLanguageState(resolved);
    return resolved;
  };

  return { language, setLanguage, t };
}

export default { t, getLanguage, setLanguagePreference, useLanguage, translations };
